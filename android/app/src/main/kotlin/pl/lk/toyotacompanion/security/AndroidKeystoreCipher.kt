package pl.lk.toyotacompanion.security

import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import java.security.KeyStore
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/**
 * AES-256-GCM with a non-exportable key in the "AndroidKeyStore" (ADR-007).
 *
 * - The key needs no user authentication, so background sync can decrypt while the phone is locked.
 * - No StrongBox: not available on every device, and the threat model (ADR-007) does not require it.
 * - The IV is generated by the cipher (Keystore forbids caller-chosen IVs) and stored in the blob.
 *
 * Not unit-tested: Robolectric has no AndroidKeyStore (docs/SECURITY.md).
 */
class AndroidKeystoreCipher(private val alias: String = KEY_ALIAS) : SecretCipher {
    override fun encrypt(plain: ByteArray, aad: ByteArray): ByteArray {
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.ENCRYPT_MODE, key())
        cipher.updateAAD(aad)
        val iv = cipher.iv
        check(iv.size == GCM_IV_BYTES) { "Unexpected IV length" }
        return byteArrayOf(BLOB_VERSION) + iv + cipher.doFinal(plain)
    }

    override fun decrypt(blob: ByteArray, aad: ByteArray): ByteArray {
        if (blob.size <= 1 + GCM_IV_BYTES || blob[0] != BLOB_VERSION) {
            throw UnsupportedSecretBlobException()
        }
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.DECRYPT_MODE, key(), GCMParameterSpec(GCM_TAG_BITS, blob, 1, GCM_IV_BYTES))
        cipher.updateAAD(aad)
        return cipher.doFinal(blob, 1 + GCM_IV_BYTES, blob.size - 1 - GCM_IV_BYTES)
    }

    private fun key(): SecretKey {
        existingKey()?.let { return it }
        // UI and worker may get here together: a second generateKey would replace the first
        // key and make everything encrypted with it unreadable.
        synchronized(KEY_LOCK) {
            existingKey()?.let { return it }
            return generateKey()
        }
    }

    private fun existingKey(): SecretKey? {
        val keyStore = KeyStore.getInstance(ANDROID_KEYSTORE).apply { load(null) }
        return keyStore.getKey(alias, null) as? SecretKey
    }

    private fun generateKey(): SecretKey {
        val generator = KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, ANDROID_KEYSTORE)
        generator.init(
            KeyGenParameterSpec.Builder(alias, KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT)
                .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
                .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
                .setKeySize(256)
                .setUserAuthenticationRequired(false)
                .build(),
        )
        return generator.generateKey()
    }

    companion object {
        const val KEY_ALIAS = "toyota-companion-secrets-v1"
        private val KEY_LOCK = Any()
        private const val ANDROID_KEYSTORE = "AndroidKeyStore"
        private const val TRANSFORMATION = "AES/GCM/NoPadding"
    }
}
